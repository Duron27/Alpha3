#!/usr/bin/env python3
"""Turns `gn desc --format=json` output for ANGLE into angle_sources.cmake.

Only needed to update the source lists for a new ANGLE version, the normal build does not run it.

How to produce the input (once per ANGLE version, needs the ANGLE checkout with its DEPS fetched and a gn binary):

    gn gen out --args='<the args below>'     # or write them to out/args.gn and create an empty out/build.ninja

The args (what the CMake build reproduces):

    target_os = "android"
    target_cpu = "arm64"
    arm_control_flow_integrity = "none"
    use_thin_lto = true
    thin_lto_enable_optimizations = true
    angle_enable_vulkan = true
    is_component_build = false
    is_debug = false
    angle_enable_gl = false
    angle_libs_suffix = "_angle"
    android_ndk_api_level = 26
    angle_expose_non_conformant_extensions_and_versions = true

Then, for each label in TARGETS below (plus //:angle_program_version_id):
     gn desc out <label> --format=json > desc/<label with / and : replaced by __>.json

Usage:  gen_sources.py <desc dir> <angle root> <output .cmake> [angle commit] [gn build dir]
"""
import glob
import json
import os
import sys

# CMake name -> gn label. Each becomes ANGLE_SRC_<name> with the compiled files of that target.
TARGETS = {
    'xxhash': '//:xxhash',
    'common': '//:angle_common',
    'common_shader_state': '//:angle_common_shader_state',
    'image_util': '//:angle_image_util',
    'gpu_info_util': '//:angle_gpu_info_util',
    'preprocessor': '//:preprocessor',
    'translator': '//:translator',
    'version': '//:angle_version',
    'version_info': '//:angle_version_info',
    'spirv_base': '//src/common/spirv:angle_spirv_base',
    'spirv_builder': '//src/common/spirv:angle_spirv_builder',
    'spirv_parser': '//src/common/spirv:angle_spirv_parser',
    'vulkan_loader': '//src/common/vulkan:angle_libvulkan_loader',
    'vulkan_icd': '//src/common/vulkan:angle_vulkan_icd',
    'vk_mem_alloc': '//src/libANGLE/renderer/vulkan:angle_vk_mem_alloc_wrapper',
    'volk': '//src/third_party/volk:volk',
    'null_backend': '//src/libANGLE/renderer/null:angle_null_backend',
    'vulkan_backend': '//src/libANGLE/renderer/vulkan:angle_vulkan_backend',
    'libangle': '//:libANGLE_no_vulkan',
    'frame_capture_mock': '//:angle_frame_capture_mock',
    'compression': '//third_party/zlib/google:compression_utils_portable',
    'egl_loader': '//:libEGL_egl_loader',
    'libEGL': '//:libEGL',
    'libGLESv1_CM': '//:libGLESv1_CM',
    'libGLESv2': '//:libGLESv2',
    'feature_support': '//:libfeature_support',
}
COMPILED = ('.c', '.cc', '.cpp')


def load(path):
    text = open(path).read()
    return json.loads(text[text.find('{\n'):])  # gn prints warnings before the JSON


def main():
    desc_dir, root, out = sys.argv[1:4]
    commit = sys.argv[4] if len(sys.argv) > 4 else 'unknown'
    build_dir = sys.argv[5] if len(sys.argv) > 5 else os.path.join(os.path.dirname(os.path.abspath(root)), 'out')
    targets = {}
    for f in glob.glob(os.path.join(desc_dir, '*.json')):
        for label, t in load(f).items():
            targets[label.split('(')[0]] = t

    seen = {}
    lines = [
        '# Generated by tools/gen_sources.py from `gn desc` (Android arm64, Vulkan only, args in tools/gen_sources.py).',
        f'# ANGLE commit {commit}. Paths are relative to the ANGLE source root. Do not edit by hand.',
        '',
    ]
    for name, label in TARGETS.items():
        sources = []
        for s in targets[label].get('sources', []):
            if not s.startswith('//') or not s.endswith(COMPILED):
                continue
            rel = s[2:]
            if not os.path.exists(os.path.join(root, rel)):
                sys.exit(f'{label}: {rel} does not exist in {root}')
            if rel in seen:
                sys.exit(f'{rel} is in both {seen[rel]} and {name}')
            seen[rel] = name
            sources.append(rel)
        lines.append(f'set(ANGLE_SRC_{name}')
        lines += [f'    {s}' for s in sorted(sources)]
        lines += [')', '']

    # Files that the shader program cache version is hashed over (ANGLEShaderProgramVersion.h).
    # gn writes them relative to the build directory, make them relative to the ANGLE root.
    files = []
    for s in targets['//:angle_program_version_id']['response_file_contents']:
        files.append(os.path.relpath(os.path.normpath(os.path.join(build_dir, s)), root))
    missing = [f for f in files if not os.path.exists(os.path.join(root, f))]
    if missing:
        sys.exit(f'program version files not found: {missing[:5]}')
    lines.append('set(ANGLE_PROGRAM_VERSION_FILES')
    lines += [f'    {p}' for p in files]
    lines += [')', '']

    open(out, 'w').write('\n'.join(lines))
    print(f'{len(seen)} compiled sources in {len(TARGETS)} groups, {len(files)} program version files -> {out}')


if __name__ == '__main__':
    main()
