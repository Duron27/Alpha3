# export.py <model.pt> <out .hpp>: the weights as C++ arrays for support/src/aiupscale.cpp
import sys, torch
ck = torch.load(sys.argv[1], map_location='cpu'); st = ck['state']
convs = [k[:-len('.weight')] for k in st if k.endswith('.weight') and st[k].dim() == 4]
prelus = [k for k in st if k.endswith('.weight') and st[k].dim() == 1]
out = ['// Generated by the texture upscaler training (export.py) from ' + sys.argv[1].split('/')[-1] + ': do not edit.',
       '// Weights of each 3x3 convolution as [ky][kx][in][out], then its bias [out] and PReLU slopes [out] (none on the last).',
       '#pragma once', '#define AI_UPSCALE_AVAILABLE 1', 'namespace Alpha3::AiUpscaleWeights', '{',
       f'    constexpr int kFeatures = {ck["feat"]}, kConvs = {ck["convs"]};']
import hashlib
digest = hashlib.sha1(b''.join(v.numpy().tobytes() for v in st.values())).hexdigest()[:8]
out.append(f'    // a hash of the weights: converted textures are cached under it')
out.append(f'    inline constexpr const char* kVersion = "{ck["feat"]}x{ck["convs"]}-{digest}";')
def arr(name, t):
    vals = ', '.join(f'{v:.8g}f' for v in t.flatten().tolist())
    out.append(f'    alignas(16) inline constexpr float {name}[{t.numel()}] = {{ {vals} }};')
for i, c in enumerate(convs):
    arr(f'w{i}', st[c + '.weight'].permute(2, 3, 1, 0).contiguous())  # out,in,ky,kx -> ky,kx,in,out
    arr(f'b{i}', st[c + '.bias'])
    if i < len(prelus): arr(f'a{i}', st[prelus[i]])
out.append('}')
n = len(convs)
out.append('#define AI_UPSCALE_WEIGHTS ' + ', '.join(f'AiUpscaleWeights::w{i}' for i in range(n)))
out.append('#define AI_UPSCALE_BIASES ' + ', '.join(f'AiUpscaleWeights::b{i}' for i in range(n)))
out.append('#define AI_UPSCALE_SLOPES ' + ', '.join(f'AiUpscaleWeights::a{i}' for i in range(n - 1)))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(convs), 'convolutions,', sum(v.numel() for v in st.values()), 'numbers')
